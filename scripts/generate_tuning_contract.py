"""Generate matching C/C++ parameter IDs and guards for ESP and both Rear builds."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TARGETS = [ROOT/'firmware'/folder/'djy_tuning_parameters.h' for folder in (
    'esp32_ev_gateway/include', 'stm32_rear_binary/Core/Inc', 'stm32_rear_uart/Core/Inc')]

def render():
    data = json.loads((ROOT/'protocol/tuning_parameters.json').read_text(encoding='utf8'))
    lines = ['/* Generated by scripts/generate_tuning_contract.py; do not edit. */',
             '#ifndef DJY_TUNING_PARAMETERS_H', '#define DJY_TUNING_PARAMETERS_H',
             '#include <stdint.h>', '#include <stdbool.h>',
             f'#define DJY_TUNING_SCHEMA_VERSION {data["schema_version"]}u',
             '/* IDs/scales reserve an extension contract, NOT an enabled new UART packet. */',
             'enum {']
    for p in data['parameters']:
        lines.append(f'    DJY_PARAM_{p["symbol"]} = {p["id"]}u,')
    lines += ['};']
    for p in data['parameters']:
        lines.append(f'#define DJY_PARAM_{p["symbol"]}_SCALE {p["scale"]}')
    lines += ['typedef enum { DJY_TUNING_OK=0, DJY_TUNING_UNSUPPORTED=1,',
              '    DJY_TUNING_RANGE=2, DJY_TUNING_VERSION=3 } DjyTuningStatus;',
              '/* Signed scaled integer. No packed struct is transmitted on UART. */',
              'typedef struct { uint16_t schema_version, parameter_id; uint32_t request_id;',
              '    int32_t value; } DjyTuningUpdate;',
              'static inline DjyTuningStatus djy_tuning_validate(uint16_t id, int32_t value) {',
              '    switch (id) {']
    for p in data['parameters']:
        if p['access'] == 'live':
            lines += [f'    case DJY_PARAM_{p["symbol"]}:',
                      f'        return value >= {p["min"]} && value <= {p["max"]} &&',
                      f'            (value - {p["min"]}) % {p["step"]} == 0 ? DJY_TUNING_OK : DJY_TUNING_RANGE;']
    lines += ['    default: return DJY_TUNING_UNSUPPORTED;', '    }', '}',
              'static inline DjyTuningStatus djy_tuning_validate_update(const DjyTuningUpdate *p) {',
              '    if (!p || p->schema_version != DJY_TUNING_SCHEMA_VERSION) return DJY_TUNING_VERSION;',
              '    return djy_tuning_validate(p->parameter_id, p->value);', '}',
              '#endif', '']
    return '\n'.join(lines)

def main():
    parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
    expected=render()
    for path in TARGETS:
        if args.check:
            if not path.exists() or path.read_text(encoding='utf8') != expected:
                raise SystemExit(f'Generated tuning contract is stale: {path}')
        else:
            path.write_text(expected,encoding='utf8')
    print('Tuning contract: '+('verified' if args.check else 'generated')+' for ESP and both Rear variants')

if __name__=='__main__': main()
